type Spec = [stage: string, title: string, scene: string, grammar: string[], vocabulary: string[]];

const levelForStage = (stage: string): CourseLevel => {
  if (/N1|高级|Advanced/.test(stage)) return 'N1';
  if (/N2|中高级|中上级|B2|Upper/.test(stage)) return 'N2';
  if (/N3|中级|B1|Intermediate/.test(stage)) return 'N3';
  if (/N4|A2|Elementary 2|初级 II|GENKI II/.test(stage)) return 'N4';
  return 'N5';
};

const fromSpecs = (specs: Spec[]): Lesson[] => specs.map(([stage, title, scene, grammar, vocabulary], index) => ({
  level: levelForStage(stage),
  stage,
  number: index + 1,
  title,
  scene,
  goals: [`在“${scene}”中自然交流`, `主动使用：${grammar.slice(0, 2).join('、')}`],
  grammar,
  vocabulary,
  review: index ? specs[index - 1][3].slice(0, 2) : [],
}));

const stageSpecs = (stage: string, titles: string[], grammar: string[][], vocabulary: string[][]): Spec[] =>
  titles.map((title, index) => [
    stage,
    title,
    `在“${title}”的真实生活场景中与美绪完成交流任务`,
    grammar[index % grammar.length],
    vocabulary[index % vocabulary.length],
  ]);

const numberedStageSpecs = (
  stage: string,
  count: number,
  topics: string[],
  grammar: string[][],
  vocabulary: string[][],
): Spec[] => Array.from({ length: count }, (_, index) => {
  const round = Math.floor(index / topics.length);
  const title = `${topics[index % topics.length]}${round ? ` · 应用 ${round + 1}` : ''}`;
  return [stage, title, `围绕“${topics[index % topics.length]}”完成一段有明确目标的角色对话`, grammar[index % grammar.length], vocabulary[index % vocabulary.length]];
});

