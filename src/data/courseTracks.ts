export const getCourseTrack = (id: string) => courseTracks.find((track) => track.id === id) || courseTracks[0];
export const getTrackLessons = (track: CourseTrack, stage: string) => track.lessons.filter((lesson) => lesson.stage === stage);
export const getTrackLesson = (track: CourseTrack, stage: string, number: number) => {
  const stageLessons = getTrackLessons(track, stage);
  return stageLessons[Math.min(Math.max(number, 1), stageLessons.length) - 1];
};
