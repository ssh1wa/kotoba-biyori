export const courseLevels: CourseLevel[] = ['N5', 'N4', 'N3', 'N2', 'N1'];

export const getLessonsForLevel = (level: CourseLevel) =>
  lessons.filter((lesson) => lesson.level === level);

export const getLesson = (level: CourseLevel, number: number) => {
  const levelLessons = getLessonsForLevel(level);
  return levelLessons[Math.min(Math.max(number, 1), levelLessons.length) - 1];
};
